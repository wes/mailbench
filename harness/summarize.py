#!/usr/bin/env python3
"""The published numbers, derived from the raw output and nothing else.

    python3 harness/summarize.py results/<run>            write results/<run>/summary.json
    python3 harness/summarize.py results/<run> --check    fail if summary.json is not what raw/ gives
    python3 harness/summarize.py --all [--check]          every run in results/

The website reads summary.json. CI regenerates it from raw/ on every pull
request and fails if a single number differs, so a number on the site can
always be traced to the instrument's own lines — nobody, including whoever
maintains this repository, can edit one by hand.

A run imported from before raw output was kept has no raw/ directory; its
summary.json is hand-transcribed, and its run.json says where from.
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from datetime import datetime, timezone
from pathlib import Path

from mailbench_data import ROOT, calibration, current, load_client, load_metrics, metric_values, read_lines

COMMENT = ("Generated by harness/summarize.py from raw/. Do not edit: CI regenerates this file "
           "and fails if it differs.")


def summarize(run_dir: Path) -> dict:
    raw = run_dir / "raw"
    metrics = load_metrics()
    clients = []
    display_hz = set()
    for path in sorted(raw.glob("*.jsonl")):
        if path.stem == "calibration":
            continue
        session, measured = current(read_lines(path))
        if not session:
            continue
        if measured["display_hz"]:
            display_hz.add(measured["display_hz"])
        base, _, tag = path.stem.partition("@")
        definition = load_client(base) or {}
        entry = {
            "id": base,
            "name": definition.get("name", base),
            "version": session.get("version") or None,
            "measured_on": (datetime.fromtimestamp(session["at"], timezone.utc).date().isoformat()
                            if session.get("at") else None),
            "metrics": metric_values(path.stem, measured, metrics),
        }
        if tag:
            entry["tag"] = tag
        clients.append(entry)

    out: dict = {"$comment": COMMENT, "run": run_dir.name, "source": "raw"}
    # Every client in one run was seen through the same display; if they were
    # not, the run is not one run, and validate.py says so.
    out["display_hz"] = (None if not display_hz
                         else sorted(display_hz)[0] if len(display_hz) == 1 else sorted(display_hz))
    cal_path = raw / "calibration.jsonl"
    if cal_path.exists():
        rows = calibration(read_lines(cal_path))
        if rows:
            out["calibration"] = {
                "rows": rows,
                "overhead_ms": round(statistics.median(r["overhead_ms"] for r in rows), 1),
            }
    out["clients"] = clients
    return out


def dumps(summary: dict) -> str:
    return json.dumps(summary, indent=2, ensure_ascii=False) + "\n"


def one(run_dir: Path, check: bool) -> bool:
    target = run_dir / "summary.json"
    if not (run_dir / "raw").is_dir():
        if not target.exists():
            print(f"{run_dir.name}: no raw/ and no summary.json", file=sys.stderr)
            return False
        return True  # imported; validate.py checks run.json says so
    text = dumps(summarize(run_dir))
    if check:
        if not target.exists() or target.read_text() != text:
            print(f"{run_dir.name}: summary.json is not what raw/ gives. "
                  f"Run: python3 harness/summarize.py results/{run_dir.name}", file=sys.stderr)
            return False
        return True
    target.write_text(text)
    print(f"wrote {target}", file=sys.stderr)
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("run", type=Path, nargs="?")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if args.all:
        dirs = sorted(p for p in (ROOT / "results").iterdir() if p.is_dir())
    elif args.run:
        dirs = [args.run.resolve()]
    else:
        ap.error("give a run directory, or --all")
    ok = all([one(d, args.check) for d in dirs])
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
